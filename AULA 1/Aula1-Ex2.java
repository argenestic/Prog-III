public class Ex2 {
    public static void main(String[] args) {
        boolean chove = true;
        boolean estaFrio = false;
        boolean feriado = true;

        if (chove) {
            System.out.println("Esta chovendo");
        } else {
            System.out.println("Nao esta chovendo");
        }

        if (estaFrio) {
            System.out.println("Esta frio");
        } else {
            System.out.println("Nao esta frio");
        }

        if (feriado) {
            System.out.println("Hoje e feriado");
        } else {
            System.out.println("Hoje nao e feriado");
        }
    }
}
